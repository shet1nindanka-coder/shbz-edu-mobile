// `teacherStudents` reads and the deferred jobs of OTHER members, end to end: a teacher's read arms the
// timer of a seeded in-flight row (`ctx.jobs.touch`) and the real handler — the student-work member's
// check, the planner's generation — finishes it. `mock-teacher-students.test.ts` proves the timing with
// stand-in handlers; here nothing is replaced (docs/spec/90-addendum-6.md §5, 04 §5.2).
//
// Node's test runner and assert are typed by referencing only their declaration files: the project does not
// load `@types/node` globally (it would change DOM / React Native globals such as the timer return types).
/// <reference path="../node_modules/@types/node/assert.d.ts" />
/// <reference path="../node_modules/@types/node/assert/strict.d.ts" />
/// <reference path="../node_modules/@types/node/test.d.ts" />
import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { createTestMock } from "../src/mock/testing";

const ANNA = "teacher@example.com";

describe("teacherStudents reads drive the other members' jobs", () => {
  it("a running homework check seen only by the teacher ends with real verdicts", async () => {
    const mock = createTestMock();
    await mock.signIn(ANNA);
    const running = async () =>
      (await mock.api.teacherStudents.getStudentHomeworks("usr_artem")).assignments.find((assignment) => assignment.id === "hw_artem_running")!;

    const first = await running();
    assert.equal(first.latestCheck!.status, "CHECKING");
    assert.equal(first.photos.length, 2);
    const snapshot = first.latestCheck!.photos.length;

    mock.clock.advance(7999);
    assert.equal((await running()).latestCheck!.status, "CHECKING");
    mock.clock.advance(1);
    const done = await running();
    assert.equal(done.latestCheck!.id, first.latestCheck!.id);
    assert.equal(done.latestCheck!.status, "DONE");
    assert.ok(done.latestCheck!.checkedAt !== null);
    // The finished check consumed its batch: the photos live on in the check only.
    assert.equal(done.photos.length, 0);
    assert.equal(done.latestCheck!.photos.length, snapshot);
    // Every result names a number of the homework and carries the staff-only flags as booleans.
    const labels = new Set(done.numbers.map((number) => number.number));
    for (const result of done.latestCheck!.results) {
      assert.ok(labels.has(result.number));
      assert.equal(typeof result.copySuspected, "boolean");
      assert.equal(typeof result.injectionSuspected, "boolean");
    }
    // Counters follow the colours the verdicts wrote through the progress rules.
    const solved = done.numbers.filter((number) => number.status === "GREEN" || number.status === "YELLOW").length;
    assert.equal(done.solvedCount, solved);
    assert.equal(mock.store.jobs.by("refId", first.latestCheck!.id).length, 0);
  });

  it("a pending plan polled from the student card is generated by the planner", async () => {
    const mock = createTestMock();
    await mock.signIn(ANNA);
    const lesson = async () => (await mock.api.teacherStudents.listStudentLessons("usr_ilya")).lessons.find((entry) => entry.id === "les_ilya_tomorrow")!;

    const first = await lesson();
    assert.deepEqual([first.planPending, first.planError, first.items.length], [true, null, 0]);
    // The card polls the plan status of the pending lesson every 2.5 s.
    mock.clock.advance(2500);
    const status = await mock.api.planner.getLessonStatus("les_ilya_tomorrow");
    assert.equal(status.pending, 1);
    mock.clock.advance(2500);
    const ready = await mock.api.planner.getLessonStatus("les_ilya_tomorrow");
    assert.deepEqual([ready.pending, ready.ready, ready.failed], [0, 1, 0]);

    const after = await lesson();
    assert.deepEqual([after.planPending, after.planError], [false, null]);
    assert.ok(after.items.length > 0);
    assert.ok(after.items.some((item) => !item.isExtra));
    assert.ok(after.items.every((item) => item.result === null));
    assert.equal(after.participantId, first.participantId);
  });
});
